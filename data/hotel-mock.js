    var norm = root.BMAccommodation && root.BMAccommodation.normalizeProperty
      ? root.BMAccommodation.normalizeProperty
      : function (x) { return x; };

    var live = (supabaseRows || []).map(function (row) {
      return Object.assign({}, norm(row), { source: row.source || "supabase", is_mock: false, data_badge: "Verified" });
    });

    var keys = {};
    live.forEach(function (row) {
      var key = String(row.name || "").trim().toLowerCase() + "|" + String(row.location || "").trim().toLowerCase();
      if (key !== "|") keys[key] = true;
      if (row.id != null) keys["id:" + String(row.id)] = true;
    });

