    const LANG_KEY = "bm_lang";
    let currentLang = "en";

    function getSavedLang() {
      try {
        const params = new URLSearchParams(window.location.search);
        const q = params.get("lang");
        if (q && translations[q]) return q;
      } catch (e) {}
      try {
        const saved = localStorage.getItem(LANG_KEY);
        if (saved && translations[saved]) return saved;
      } catch (e) {}
      return "en";
    }

    function t(key, fallback) {
      const pack = translations[currentLang] || translations.en;
      return (pack && pack[key]) || (translations.en && translations.en[key]) || fallback || key;
    }

    function lookup(lang, key) {
      if (translations[lang] && translations[lang][key] != null && translations[lang][key] !== "") {
        return translations[lang][key];
      }
      if (lang !== "en" && translations.en && translations.en[key] != null) {
        return translations.en[key];
      }
      return null;
    }

    function setLanguage(lang) {
      if (!translations[lang]) lang = "en";
      currentLang = lang;
      try {
        localStorage.setItem(LANG_KEY, lang);
      } catch (e) {}
      document.documentElement.lang = lang;

      document.querySelectorAll("[data-i18n]").forEach((el) => {
        const key = el.getAttribute("data-i18n");
        const value = lookup(lang, key);
        if (value != null) el.textContent = value;
      });

      document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
        const key = el.getAttribute("data-i18n-placeholder");
        const value = lookup(lang, key);
        if (value != null) el.setAttribute("placeholder", value);
      });

      document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
        const key = el.getAttribute("data-i18n-alt");
        const value = lookup(lang, key);
        if (value != null) el.setAttribute("alt", value);
      });

      document.querySelectorAll(".lang-switch button").forEach((btn) => {
        btn.classList.toggle("active", btn.dataset.lang === lang);
      });

      if (window.BM_I18N && Array.isArray(window.BM_I18N.onChange)) {
        window.BM_I18N.onChange.forEach((fn) => {
          try {
            fn(lang);
          } catch (e) {}
        });
      }
    }

    window.BM_I18N = {
      getLang: () => currentLang,
      setLanguage,
      t,
      translations,
      onChange: []
    };

    document.querySelectorAll(".lang-switch button").forEach((button) => {
      button.addEventListener("click", () => {
        const lang = button.dataset.lang;
        if (lang === "zh") {
          window.location.href = "https://visitmongoliatours.com/";
          return;
        }
        if (lang !== "en" && lang !== "ja" && lang !== "ko" && lang !== "mn") return;
        setLanguage(lang);
      });
    });

    setLanguage(getSavedLang());

    document.querySelectorAll(".yt-facade").forEach((button) => {
      button.addEventListener("click", () => {
        const id = button.getAttribute("data-yt");
        if (!id) return;
        const frame = document.createElement("iframe");
        frame.src = "https://www.youtube-nocookie.com/embed/" + id + "?autoplay=1";
        frame.title = button.textContent || "Mongolia video";
        frame.allow = "autoplay; fullscreen";
        frame.allowFullscreen = true;
        button.replaceWith(frame);
      });
    });
